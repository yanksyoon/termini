"""Public API for termini.decision — the model-driven operator decision adapter.

Exposes the adapter functions (:func:`decide`, :func:`parse`, :func:`render`)
and the frozen contract structures (``DecisionInput``, ``DecisionResponse``,
``DecisionError``, ``ACTION_SPACE``, ``FALLBACK_REASONS``).

This package is the *inference side* of the operator decision step
(``docs/contracts/operator-decision.md`` §6). It is **not** the security
boundary: :func:`parse` guarantees the model's answer is well-shaped, and the
controller's guardrail (G1–G8) is what authorizes it before execution. The only
safe consumption path is the controller's ``ModelDecisionProvider``; a caller
that executes a :class:`DecisionResponse` directly is bypassing the guardrail.
"""

